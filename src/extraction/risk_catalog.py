def applicable_rules(profile):
    selected = deepcopy([item for item in RULES if profile.contract_type in item["kinds"] and profile.user_side in item["sides"]])
    specific = {
        'payment_dependency': ('ст. 328, 314', 'ст. 516', 'ст. 781'),
        'acceptance_silence': ('ст. 421', 'ст. 513', 'ст. 783; применимость правил о приёмке зависит от предмета услуг'),
        'acceptance_discretion': ('ст. 309, 328', 'ст. 513, 516', 'ст. 781'),
    }
    for item in selected:
        if item['id'] in specific:
            general, supply, services = specific[item['id']]
            item['legal_references'][0]['articles'] = general
            source = 'supply' if profile.contract_type == 'supply' else 'services'
            item['legal_references'].append({**SOURCES[source], 'articles': supply if source == 'supply' else services})
        if item['id'] in {'price_change', 'services_customer_exit'}:
            item['legal_references'].append(SOURCES['obligations'])
        if item['id'] in {'uncapped_penalty', 'intentional_exemption'}:
            item['legal_references'].append(SOURCES['liability'])
    return selected
